# Let's just find the start and end of { 'id': 2 ... }
pattern = re.compile(r"\{\s*'id': 2, 'tipo': 'Presencial'.*?'bibliografia': 'Porter, M.*?\}", re.DOTALL)

# Format c2 back to string
def dict_to_str(d):
    res = "{\n"
    for k, v in d.items():
        if isinstance(v, str) and '<' in v:
            res += f"        '{k}': '''{v}''',\n"
        elif isinstance(v, str):
            res += f"        '{k}': '{v}',\n"
        else:
            res += f"        '{k}': {v},\n"
    res += "    }"
    return res

